let storiesStore: ImpactStory[] = [...INITIAL_STORIES];

export function getStories(): ImpactStory[] {
  return storiesStore;
}

export function getStoriesByEventSlug(slug: string): ImpactStory[] {
  return storiesStore.filter((s) => s.eventSlug === slug);
}

export function addStory(story: Omit<ImpactStory, "id">): ImpactStory {
  const newStory: ImpactStory = {
    ...story,
    id: `story-${Date.now()}`,
  };
  storiesStore = [newStory, ...storiesStore];
  return newStory;
}

export function updateStory(id: string, updates: Partial<ImpactStory>): ImpactStory | null {
  const index = storiesStore.findIndex((s) => s.id === id);
  if (index === -1) return null;
  storiesStore[index] = { ...storiesStore[index], ...updates };
  return storiesStore[index];
}

export function deleteStory(id: string): boolean {
  const initialLength = storiesStore.length;
  storiesStore = storiesStore.filter((s) => s.id !== id);
  return storiesStore.length < initialLength;
}
